// Additive preservation check. Does not replace canonical validation, Goal
// Controller, owner decisions, existing security gates or reverse audit.
export function collectResearch(text) {
  return text.split(/\r?\n/).filter(l => /^\| R\d+ \|/.test(l))
    .map(l => ({ id: l.split('|')[1].trim(), definition: l.trim() }));
}
export function collectRoadmap(text) {
  return text.split(/\r?\n/).filter(l => /^(## Phase \d+ - |### GAI Phase \d+ - )/.test(l))
    .map(l => ({ id: (l.startsWith('### GAI') ? 'GAI-' : 'CREATOR-') + l.match(/Phase (\d+)/)[1], definition: l.trim() }));
}
function ordered(value) {
  if (Array.isArray(value)) return value.map(ordered);
  if (value !== null && typeof value === 'object')
    return Object.fromEntries(Object.keys(value).sort().map(k => [k, ordered(value[k])]));
  return value;
}
const equal = (a,b) => JSON.stringify(ordered(a)) === JSON.stringify(ordered(b));
const contains = (current, old) => Array.isArray(current) && Array.isArray(old) && old.every(x => current.includes(x));
function index(rows, label, errors) {
  const result = new Map();
  if (!Array.isArray(rows)) { errors.push(label + ': expected an array'); return result; }
  for (const row of rows) {
    if (!row || typeof row.id !== 'string' || !row.id.trim()) { errors.push(label + ': invalid id'); continue; }
    if (result.has(row.id)) errors.push(label + ': duplicate ' + row.id);
    else result.set(row.id, row);
  }
  return result;
}
export function checkInheritance(baseline, current) {
  const errors = [];
  if (baseline?.schema_version !== 1 || !/^[a-f0-9]{40}$/.test(baseline?.baseline_main ?? ''))
    errors.push('Invalid historical baseline');
  // This historical capture is not regenerated by this program.
  for (const [key, expected] of Object.entries({requirements:341,cognitive:17,research:20,roadmap:35})) {
    if (!Array.isArray(baseline?.[key]) || baseline[key].length !== expected)
      errors.push('Historical inventory count differs: ' + key);
  }
  const compare = (key, predicate) => {
    const original = index(baseline?.[key], 'baseline ' + key, errors);
    const present = index(current?.[key], 'current ' + key, errors);
    for (const [id, row] of original) {
      const actual = present.get(id);
      if (!actual) { errors.push(key + ': missing ' + id); continue; }
      predicate(row,actual,field => errors.push(key + ': ' + id + ' ' + field + ' changed; review required'));
    }
  };
  compare('requirements',(old,now,fail)=>{
    for (const k of ['title','description']) if (typeof now[k] !== 'string' || old[k] !== now[k]) fail(k);
    if (!contains(now.required_evidence,old.required_evidence)) fail('required_evidence floor');
    if (!contains(now.source_decisions ?? [],old.source_decisions ?? [])) fail('source_decisions provenance');
  });
  compare('cognitive',(old,now,fail)=>{if (old.title !== now.title) fail('title');});
  compare('research',(old,now,fail)=>{if (old.definition !== now.definition) fail('definition');});
  compare('roadmap',(old,now,fail)=>{if (old.definition !== now.definition) fail('definition');});
  compare('allocations',(old,now,fail)=>{
    if (old.decision_id !== now.decision_id) fail('decision_id');
    if (!contains(now.required_evidence,old.required_evidence)) fail('required_evidence floor');
  });
  compare('decisions',(old,now,fail)=>{
    if (!equal(old.source,now.source)) fail('source provenance');
    if (!contains(now.canonical_ids,old.canonical_ids)) fail('canonical links');
  });
  if (!Array.isArray(current?.mirror) || !equal(current.requirements,current.mirror)) errors.push('Canonical Markdown and JSON full rows differ');
  return errors;
}
export function loadInputs(root) {
  const read = p => fs.readFileSync(path.join(root,p),'utf8');
  const json = p => JSON.parse(read(p));
  const baseline = json('docs/handoffs/goriq-inheritance/baseline-20261126.json');
  const matrix = json('docs/jarvis-requirements.json');
  const markdown = read('docs/JARVIS_PRODUCT_SPEC.md');
  const mirror = [...markdown.matchAll(/\x60\x60\x60json\r?\n([\s\S]*?)\r?\n\x60\x60\x60/g)].map(m => JSON.parse(m[1]));
  const current = {
    requirements:matrix.requirements,mirror,
    cognitive:json('docs/goriq-cognitive-status.json').components,
    research:collectResearch(read('docs/research-ops-r1-r20.md')),
    roadmap:collectRoadmap(read('ROADMAP.md')),
    allocations:json('docs/jarvis-additional-requirements.json').allocations,
    decisions:json('docs/jarvis-owner-decisions.json').decisions.map(d => ({id:d.id,source:d.source,canonical_ids:d.canonical.map(c=>c.id)}))
  };
  return {baseline,current};
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.slice(2).some(x=>x!=='--check')) throw Error('Read-only --check; no automatic rebaseline');
    const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
    const {baseline,current}=loadInputs(root);
    const errors=checkInheritance(baseline,current);
    if(errors.length) { console.error(errors.join('\n')); process.exitCode=1; }
    else console.log(JSON.stringify({status:'PASS',requirements:baseline.requirements.length,cognitive:baseline.cognitive.length,research:baseline.research.length,roadmap:baseline.roadmap.length,functional_completion_claim:false}));
  } catch (e) { console.error(e.message); process.exitCode=1; }
}
